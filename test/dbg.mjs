import { createRequire } from 'node:module';
import http from 'node:http';
import { readFileSync } from 'node:fs';
const require = createRequire('/opt/npm-tools/node_modules/');
const { chromium } = require('playwright');
const html = readFileSync('dist/index.html');
const srv = http.createServer((q, r) => { r.writeHead(200, { 'content-type': 'text/html' }); r.end(html); }).listen(5178);
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
await ctx.route(/fonts\./, (r) => r.abort());
const p = await ctx.newPage();
p.on('pageerror', (e) => console.log('ERR', e.message));
await p.goto('http://localhost:5178/#notepad');
await p.waitForSelector('#newNote');
await p.click('#newNote');
await p.waitForTimeout(300);
console.log(await p.evaluate(() => { const e = document.querySelector('#ned'); const r = e.getBoundingClientRect(); return [getComputedStyle(e).display, r.width, r.height, document.querySelector('#notesWrap').className, JSON.stringify(document.querySelector('#nt').getBoundingClientRect())]; }));
await p.screenshot({ path: 'shots/dbg.png' });
await b.close(); srv.close();
